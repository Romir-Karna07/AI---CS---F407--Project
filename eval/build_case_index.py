"""
Writes eval/CASE_INDEX.md: one table per evaluation set listing every case file next to its reference, agent, format and what it tests,
so a file can be found by name or by what it exercises (the file names carry the layout / language / failure mode).

Run:  python eval/build_case_index.py
"""
import json
from pathlib import Path

EVAL = Path(__file__).resolve().parent
SETS = [
    ("Official set (held-out districts) - `python eval/run_eval.py`", "reference", "cases"),
    ("Official AI-capability set (held-out districts) - `python eval/run_eval.py --set ai`", "ai/reference", "ai/cases"),
    ("Development regression set (dev districts) - `--set dev`", "dev/reference", "dev/cases"),
    ("Development twin of the AI set (dev districts) - `--set ai-dev`", "dev/ai/reference", "dev/ai/cases"),
]

out = ["# Case index", "",
       "Generated by `python eval/build_case_index.py`. Case file stem = what the case is (`<group>_<nn>_<layout / language / failure mode>`); "
       "the reference with the expected output is in the `reference` folder of the same set (`reference/<case_id>.json`). "
       "`must fail` = the correct outcome is a clean failure that stores nothing.", ""]
for title, rdir, cdir in SETS:
    refs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((EVAL / rdir).glob("*.json"))]
    out += [f"## {title}", "", f"{len(refs)} cases; inputs in `eval/{cdir}/`, references in `eval/{rdir}/`.", "",
            "| case file | agent | format | difficulty | expected | what it tests | reference |", "|---|---|---|---|---|---|---|"]
    for r in refs:
        fname = Path(r["file"]).name
        exp = "must fail" if r.get("expected_status") == "failed" else ("fault -> recover" if r.get("inject_fault") else "complete")
        llm = " (needs model)" if r.get("needs_llm") else ""
        out.append(f"| `{fname}` | {r['agent']} | {r['source_group']} | {r.get('difficulty', '')} | {exp} | {r['description'].replace('|', '/')}{llm} | `{r['case_id']}.json` |")
    out.append("")
# ---- do the sets share data? (computed from the references: the record keys every case expects, and the bytes of every case file)
import hashlib
import itertools

NAMES = {"reference": "official", "ai/reference": "official AI", "dev/reference": "dev", "dev/ai/reference": "dev AI"}
CASE_DIRS = {"official": "cases", "official AI": "ai/cases", "dev": "dev/cases", "dev AI": "dev/ai/cases"}


def record_keys(rdir):
    keys = set()
    for p in (EVAL / rdir).glob("*.json"):
        r = json.loads(p.read_text(encoding="utf-8"))
        for rec in r.get("records", []):
            k = rec["key"]
            keys.add((r["agent"],) + tuple(str(k.get(x)).strip().casefold() for x in ("location", "period", "crop", "entity")))
    return keys


K = {NAMES[r]: record_keys(r) for r in NAMES}
H = {n: {hashlib.sha256(p.read_bytes()).hexdigest() for p in (EVAL / d).glob("*") if p.is_file()} for n, d in CASE_DIRS.items()}
out += ["## Do the sets share data?", "",
        "Nothing here is used to train a model: the pipeline is rule-based plus a hosted model that is never fine-tuned. \"Used twice\" can therefore only mean "
        "(a) the same records in the cases the code was developed on (dev) and in the cases it is scored on (official), which would be leakage, or (b) the same "
        "records scored twice. Computed now from the references (record = agent, place, period, crop, entity) and from the file bytes:", "",
        "| set A | set B | records A | records B | shared records | identical files |", "|---|---|---|---|---|---|"]
for a, b in itertools.combinations(K, 2):
    out.append(f"| {a} | {b} | {len(K[a])} | {len(K[b])} | {len(K[a] & K[b])} | {len(H[a] & H[b])} |")
out += ["",
        "* **Development vs scoring: no shared record and no shared file** (dev / dev AI are built from the dev districts, official / official AI from the held-out "
        "districts Imphal West, Thoubal, Ukhrul). The `dev` and `official` folders look alike because each official case has a *twin* in the same layout, built "
        "from different districts: the layout repeats, the data does not. `eval/contamination_check.py` enforces this on every run.",
        "* **Official vs official AI** (and dev vs dev AI) **do share records**: the held-out records are few, so the AI cases re-use them in layouts the "
        "rule-based reader cannot take (a title above the header, Tamil headers, an image ...). Both sets are only scored, not developed on (code changes made after seeing their results are disclosed in eval/README.md), and they are "
        "reported separately (`eval/phase2_metrics.csv` vs `eval/ai/ai_metrics.csv`), so no number counts a record twice. Within one set, the PDF cases also "
        "re-use the records of the CSV / JSON cases in a PDF layout (the document agent is scored on its own).",
        "* Rainfall records of the IMD and NASA POWER sources share the key (place, month) but are different values from different sources.", ""]
(EVAL / "CASE_INDEX.md").write_text("\n".join(out), encoding="utf-8")
print("wrote eval/CASE_INDEX.md")
